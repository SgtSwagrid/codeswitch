package com.alecdorrington.codeswitch.lexicon

import cats.effect.IO
import com.alecdorrington.codeswitch.services.Translator.given
import com.alecdorrington.iris.api.ProviderModel
import com.alecdorrington.megalingual.Language
import io.circe.{Codec, Decoder, Encoder}

/**
  * Where a piece of information came from, and when: each case names who gave
  * it, a dictionary or a model, then what it came from, then anything more,
  * then when, `at`.
  */
enum Source:

  /** As `dictionary` gave it at `url`, retrieved at `at`. */
  case Sourced
    (
      dictionary: Dictionary,
      url: String,
      at: Timestamp,
    )

  /**
    * Put into another language by `model`, from `original`, the text as `from`
    * gave it then, by which a translation of a text that has since changed is
    * known, at `at`.
    */
  case Translated
    (
      model: ProviderModel,
      from: Sourced,
      original: String,
      at: Timestamp,
    )

  /**
    * Generated by `model`, as no source had it, or in place of what the reader
    * or a review took out, drawing on `from`, the records whose text it was
    * given and is credited to, as a text that a model rewrote from Wiktionary's
    * is still Wiktionary's under its licence, from the passage of `page` that
    * the word was read in, if any, at `at`.
    */
  case Generated
    (
      model: ProviderModel,
      from: List[Sourced],
      page: Option[Page],
      at: Timestamp,
    )

  /** Written by the reader at `at`, in place of what was there. */
  case Edited(at: Timestamp)

  /** The records that what it gave is credited to. */
  def credits: List[Sourced] = this match
    case sourced @ Sourced(_, _, _) => List(sourced)
    case Translated(_, from, _, _)  => List(from)
    case Generated(_, from, _, _)   => from
    case Edited(_)                  => Nil

  /** The dictionaries that what it gave is credited to, each once. */
  def dictionaries: List[Dictionary] = credits.map(_.dictionary).distinct

  /**
    * The moment of the change to its lexeme that made it, if the reader or a
    * model made it in place of what was taken out (see [[Rejected]]).
    */
  def change: Option[Timestamp] = this match
    case Generated(_, _, _, at) => Some(at)
    case Edited(at)             => Some(at)
    case _                      => None

object Source:

  given Codec[Sourced] = Codec.AsObject.derived

  given Codec[Source] = Codec.AsObject.derived

/**
  * A dictionary that records come from, and that the reader may turn off, its
  * records then neither fetched nor shown, named `title` to them and described
  * by `description`, its text under the `licence` that SPDX names. Which
  * edition a record is of, if the dictionary has several, its URL says.
  */
enum Dictionary
  (
    val title: String,
    val description: String,
    val licence: String,
  ):

  /** Wiktionary, by way of Kaikki. */
  case Wiktionary
    extends Dictionary(
      "Wiktionary",
      "Written by its readers, with words of every language, by way of Kaikki.",
      "CC-BY-SA-4.0",
    )

object Dictionary:

  /** A dictionary, kept by its name, as `Wiktionary`. */
  given Codec[Dictionary] = Codec.from(
    Decoder[String].emap(name =>
      values.find(_.toString == name).toRight(s"No dictionary is $name."),
    ),
    Encoder[String].contramap(_.toString),
  )

/**
  * What `source` gave on a word, kept `raw` so that its claims can be derived
  * from it again.
  */
final case class Record(source: Source.Sourced, raw: String) derives Codec

/** A page the reader read, as it was then. */
final case class Page(url: String, title: String) derives Codec

/** A moment, in milliseconds since the epoch. */
opaque type Timestamp = Long

object Timestamp:

  def apply(millis: Long): Timestamp = millis

  /** The moment it is now. */
  val now: IO[Timestamp] = IO.realTime.map(_.toMillis)

  extension (timestamp: Timestamp)

    /** The moment in milliseconds since the epoch. */
    def millis: Long = timestamp

  given Codec[Timestamp] = Codec.from(Decoder.decodeLong, Encoder.encodeLong)

  given Ordering[Timestamp] = Ordering.Long

/** A piece of information about a lexeme, with where it came from. */
trait Attributed:
  def source: Source

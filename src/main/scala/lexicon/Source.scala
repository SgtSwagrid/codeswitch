package com.alecdorrington.codeswitch.lexicon

import cats.effect.IO
import com.alecdorrington.codeswitch.services.Translator.given
import com.alecdorrington.iris.Model
import com.alecdorrington.megalingual.Language
import io.circe.{Codec, Decoder, Encoder}

/** Where a piece of information came from, and when. */
enum Source:

  /** As `dictionary` gave it at `url`, retrieved at `at`. */
  case Sourced
    (
      dictionary: Dictionary,
      url: String,
      at: Timestamp,
    )

  /**
    * Put into another language by `model` at `at`, from `original`, the text as
    * `from` gave it then, by which a translation of a text that has since
    * changed is known.
    */
  case Translated
    (
      from: Sourced,
      original: String,
      model: Model,
      at: Timestamp,
    )

  /**
    * Generated by `model` at `at`, as no source had it, from the passage of
    * `page` that the word was read in, if any.
    */
  case Generated
    (
      model: Model,
      page: Option[Page],
      at: Timestamp,
    )

object Source:

  given Codec[Sourced] = Codec.AsObject.derived

  given Codec[Source] = Codec.AsObject.derived

/**
  * A dictionary that records come from, and that the reader may turn off, its
  * records then neither fetched nor shown, named `title` to them and described
  * by `about`, its text under the `licence` that SPDX names. Which edition a
  * record is of, if the dictionary has several, its URL says.
  */
enum Dictionary
  (
    val title: String,
    val about: String,
    val licence: String,
  ):

  /** Wiktionary, by way of Kaikki. */
  case Wiktionary
    extends Dictionary(
      "Wiktionary",
      "Written by its readers, with words of every language, by way of Kaikki. Its text is under CC BY-SA 4.0.",
      "CC-BY-SA-4.0",
    )

object Dictionary:

  /** A dictionary, kept by its name, as `Wiktionary`. */
  given Codec[Dictionary] = Codec.from(
    Decoder[String].emap(name =>
      values.find(_.toString == name).toRight(s"No dictionary is $name."),
    ),
    Encoder[String].contramap(_.toString),
  )

/**
  * What `source` gave on a word, kept `raw` so that its claims can be derived
  * from it again.
  */
final case class Record(source: Source.Sourced, raw: String) derives Codec

/** A page the reader read, as it was then. */
final case class Page(url: String, title: String) derives Codec

/** A moment, in milliseconds since the epoch. */
opaque type Timestamp = Long

object Timestamp:

  def apply(millis: Long): Timestamp = millis

  /** The moment it is now. */
  val now: IO[Timestamp] = IO.realTime.map(_.toMillis)

  extension (timestamp: Timestamp)

    /** The moment in milliseconds since the epoch. */
    def millis: Long = timestamp

  given Codec[Timestamp] = Codec.from(Decoder.decodeLong, Encoder.encodeLong)

/** A piece of information about a lexeme, with where it came from. */
trait Attributed:
  def source: Source
